import { readFile } from "node:fs/promises";
import { test, expect } from "./fixture.mjs";
import { freePort } from "./hub_server.mjs";

test("Authenticated browser manages the real Hub without a native app", { tag: "@smoke" }, async ({ page, hub }, testInfo) => {
    const pageErrors = [];
    page.on("pageerror", error => pageErrors.push(error.message));
    await page.goto(hub.url);
    await expect(page).toHaveURL(hub.url);
    await expect(page.locator(".brand-mark")).toBeVisible();
    await expect.poll(() => page.locator(".brand-mark").evaluate(image => image.complete && image.naturalWidth > 0)).toBe(true);
    const iconUrl = await page.locator('link[rel="icon"]').evaluate(link => link.href);
    const icon = await page.request.get(iconUrl);
    expect(icon.ok()).toBe(true); expect(icon.headers()["content-type"]).toContain("image/svg+xml");
    await expect(page.getByRole("button", { name: "ログイン", exact: true })).toHaveCount(0);
    await expect(page.getByLabel("管理キー", { exact: true })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "この画面の利用を終了", exact: true })).toBeVisible();
    expect((await page.context().cookies(hub.url)).every(cookie => cookie.httpOnly && cookie.sameSite === "Strict")).toBe(true);

    await page.locator('nav a[href="#device-network"]').click();
    await expect(page.getByRole("button", { name: "接続の受付を開始", exact: true })).toBeVisible();
    await page.getByLabel("このHubのIP", { exact: true }).fill("127.0.0.1");
    await page.locator("#network-port").fill(String(hub.networkPort));
    await page.getByRole("button", { name: "接続の受付を開始", exact: true }).click();
    await expect(page.getByRole("button", { name: "接続の受付を停止", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "接続ファイルを保存", exact: true })).toBeEnabled();
    const network = await hub.observeNetwork();
    expect(network.server.running).toBe(true);
    expect(network.server.bind).toBe(`https://127.0.0.1:${hub.networkPort}`);
    expect(typeof network.server.gateway_bind).toBe("string");
    const project = "Playwright browser verification";
    await page.locator('nav a[href="#shared-administration"]').click();
    await page.locator('[data-sa-operation="save_project"]').first().click();
    await page.locator("#shared-admin-label").fill(project);
    await page.locator("#shared-admin-save").click();
    await expect(page.locator("#shared-admin-notice")).toHaveText("設定を保存しました。");
    await expect(page.locator("#shared-admin-content")).toContainText(project);
    await page.reload();
    await expect(page.locator("#shared-admin-content")).toContainText(project);
    await page.locator('nav a[href="#device-network"]').click();

    const downloadPending = page.waitForEvent("download");
    await page.getByRole("button", { name: "接続ファイルを保存", exact: true }).click();
    const download = await downloadPending;
    expect(download.suggestedFilename()).toBe("hub-config.moyai-join");
    const downloaded = testInfo.outputPath(download.suggestedFilename());
    await download.saveAs(downloaded);
    const config = await readFile(downloaded, "utf8");
    expect(config).toContain(`https://127.0.0.1:${hub.networkPort}`);
    expect(config).toContain("BEGIN CERTIFICATE");
    expect(config).not.toContain("PRIVATE KEY");
    await testInfo.attach("web-network", { body: await page.screenshot({ fullPage: true }), contentType: "image/png" });

    await page.getByRole("button", { name: "接続の受付を停止", exact: true }).click();
    await expect(page.getByRole("button", { name: "接続の受付を開始", exact: true })).toBeVisible();
    expect((await hub.observeNetwork()).server.running).toBe(false);
    await page.reload();
    await expect(page.locator("#shared-admin-content")).toContainText(project);
    await expect(page.getByRole("button", { name: "接続の受付を開始", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "接続ファイルを保存", exact: true })).toBeDisabled();
    expect((await hub.command("hub_web_status")).enabled).toBe(true);

    await page.getByRole("button", { name: "Hub本体へ再接続", exact: true }).click();
    await expect(page.locator("#shared-admin-content")).toContainText(project);
    await page.locator("#manual-server-connection > summary").click();
    let manualPort = await freePort();
    while (manualPort === hub.networkPort) manualPort = await freePort();
    await page.locator("#bind").fill(`127.0.0.1:${manualPort}`);
    await page.locator("#generate-token").click();
    await page.locator("#start-server").click();
    await expect(page.locator("#stop-server")).toBeVisible();
    expect((await hub.command("hub_snapshot")).server.running).toBe(true);
    await page.locator("#stop-server").click();
    await expect(page.locator("#start-server")).toBeEnabled();
    expect((await hub.command("hub_snapshot")).server.running).toBe(false);
    await page.locator('nav a[href="#device-network"]').click();
    await testInfo.attach("web-network-viewport", { body: await page.screenshot(), contentType: "image/png" });
    await page.setViewportSize({ width: 760, height: 1000 });
    await page.getByRole("link", { name: "管理画面のURL", exact: false }).click();
    await expect(page.locator("#web-enabled-state")).toContainText("稼働中");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await testInfo.attach("web-narrow-viewport", { body: await page.screenshot(), contentType: "image/png" });
    expect(await page.evaluate(() => document.cookie)).toBe("");
    expect(pageErrors).toEqual([]);
});
